function stdHoursWithLunch(
  openTime: string,
  closeTime: string,
  closedDay: number,
  lunchStart = '13:00',
  lunchEnd = '14:00',
): WeeklyHours {
  const lunchBreak: Break[] = [{ startTime: lunchStart, endTime: lunchEnd }];
  const normalDay = { open: true, openTime, closeTime, breaks: lunchBreak };
  const closed = { open: false, openTime: '09:00', closeTime: '18:00', breaks: [] };

  const hours: Record<number, typeof normalDay> = {
    0: normalDay,
    1: normalDay,
    2: normalDay,
    3: normalDay,
    4: normalDay,
    5: normalDay,
    6: normalDay,
  };
  hours[closedDay] = closed;
  return hours as WeeklyHours;
}

function fridayEarlyCloseHours(
  openTime = '09:00',
  closeTime = '20:00',
  fridayClose = '13:00',
): WeeklyHours {
  const normalDay = { open: true, openTime, closeTime, breaks: [{ startTime: '13:00', endTime: '14:00' }] };
  const friday = { open: true, openTime, closeTime: fridayClose, breaks: [] };
  const closedSunday = { open: false, openTime: '09:00', closeTime: '18:00', breaks: [] };

  return {
    0: closedSunday,
    1: normalDay,
    2: normalDay,
    3: normalDay,
    4: normalDay,
    5: friday,
    6: { open: true, openTime, closeTime: '21:00', breaks: [{ startTime: '13:00', endTime: '14:00' }] },
  };
}

function fridayPrayerBreakHours(
  openTime = '10:00',
  closeTime = '21:00',
): WeeklyHours {
  const normalDay = { open: true, openTime, closeTime, breaks: [] };
  const friday = { open: true, openTime, closeTime, breaks: [{ startTime: '12:30', endTime: '14:30' }] };
  const closedMonday = { open: false, openTime: '10:00', closeTime: '18:00', breaks: [] };

  return {
    0: normalDay,
    1: closedMonday,
    2: normalDay,
    3: normalDay,
    4: normalDay,
    5: friday,
    6: normalDay,
  };
}

