import type { Shop, WeeklyHours, Break } from '../types';

// Helper to build standard Monday-Saturday hours with a lunch break
function stdHours(
  openTime: string,
  closeTime: string,
  lunchStart: string,
  lunchEnd: string,
): WeeklyHours {
  const lunchBreak: Break[] = [{ startTime: lunchStart, endTime: lunchEnd }];
  const openDay = { open: true, openTime, closeTime, breaks: lunchBreak };
  const closed = { open: false, openTime: '09:00', closeTime: '18:00', breaks: [] };
  return {
    0: closed,   // Sunday closed
    1: openDay,  // Monday
    2: openDay,
    3: openDay,
    4: openDay,
    5: openDay,
    6: { open: true, openTime, closeTime: '20:00', breaks: lunchBreak }, // Sat longer
  };
}

